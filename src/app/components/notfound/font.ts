// 404ボクセルシューティング用の5x7ドット絵フォント。
// 「404」「NOT FOUND」の表示に必要なグリフのみを定義する。

/** グリフの幅(列数) */
export const GLYPH_WIDTH = 5;
/** グリフの高さ(行数) */
export const GLYPH_HEIGHT = 7;

/** 各グリフは長さ GLYPH_HEIGHT の配列。各行は長さ GLYPH_WIDTH の文字列で、'#'=塗り, '.'=空。 */
// 線の太さは全グリフ1セルで統一する(混在すると字面の重さが揃わず崩れて見えるため)。
// '0' は O と区別できるよう斜線入りのスラッシュドゼロにしている。
export const GLYPHS: Readonly<Record<string, readonly string[]>> = {
  '0': ['.###.', '#...#', '#..##', '#.#.#', '##..#', '#...#', '.###.'],
  '4': ['...#.', '..##.', '.#.#.', '#..#.', '#####', '...#.', '...#.'],
  N: ['#...#', '##..#', '#.#.#', '#.#.#', '#..##', '#...#', '#...#'],
  O: ['.###.', '#...#', '#...#', '#...#', '#...#', '#...#', '.###.'],
  T: ['#####', '..#..', '..#..', '..#..', '..#..', '..#..', '..#..'],
  F: ['#####', '#....', '#....', '####.', '#....', '#....', '#....'],
  U: ['#...#', '#...#', '#...#', '#...#', '#...#', '#...#', '.###.'],
  D: ['####.', '#...#', '#...#', '#...#', '#...#', '#...#', '####.'],
};

/** 未定義文字や ' ' には null を返す。 */
export function getGlyphRows(ch: string): readonly string[] | null {
  const rows = GLYPHS[ch];
  return rows ?? null;
}
